#!/bin/sh
# Weekly OSV tripwire: open a triage issue for each GHSA newly affecting the fork base.
# usage: osv-watch.sh [TEST_ID]   TEST_ID forces one id through the pipeline (title gets [TEST] prefix)
# env:   GH_TOKEN required for writes in CI; DRY_RUN=1 prints instead of writing (no gh calls)
set -eu
DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
KNOWN="$DIR/.known-osv-ids"
VERSION=11.17.4
REPO=${GH_REPO:-zzerding/directus}
LABEL=osv-tripwire
TEST_ID=${1:-}
DRY=${DRY_RUN:-0}

TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT

curl -fsS -X POST https://api.osv.dev/v1/query \
	-d "{\"package\":{\"name\":\"directus\",\"ecosystem\":\"npm\"},\"version\":\"$VERSION\"}" \
	| jq -r '.vulns[]?.id' | sort -u > "$TMP"

new=$(comm -13 "$KNOWN" "$TMP")
if [ -n "$TEST_ID" ]; then
	new=$(printf '%s\n%s' "$new" "$TEST_ID")
fi
if [ -z "$new" ]; then
	echo "osv-watch OK: no new vulns affecting directus $VERSION"
	exit 0
fi
echo "NEW vulns affecting directus $VERSION:"
echo "$new"

if [ "$DRY" != 1 ]; then
	gh label create "$LABEL" --repo "$REPO" --color D93F0B \
		--description "New GHSA affecting fork base" >/dev/null 2>&1 || true
fi

for id in $new; do
	if [ "$DRY" != 1 ]; then
		dup=$(gh issue list --repo "$REPO" --state open --label "$LABEL" --search "$id in:title" --json number --jq 'length')
		if [ "$dup" -gt 0 ]; then
			echo "$id: open issue already exists, skip"
			continue
		fi
	fi

	if ! d=$(curl -fsS "https://api.osv.dev/v1/vulns/$id"); then
		echo "$id: detail fetch failed, skipping"
		continue
	fi
	cve=$(printf '%s' "$d" | jq -r '[(.aliases // [])[] | select(startswith("CVE-"))] | join(", ")')
	sev=$(printf '%s' "$d" | jq -r '([.severity[]? | select(.type=="CVSS_V3") | .score] | first) // "?"')
	fixed=$(printf '%s' "$d" | jq -r '[(.affected[]? | select(.package.name=="directus") | .ranges[]?.events[]?.fixed) | select(. != null)] | unique | join(", ")')
	summary=$(printf '%s' "$d" | jq -r '.summary // .details // "?"')
	refs=$(printf '%s' "$d" | jq -r '[(.references[]?.url), "https://osv.dev/vulnerability/'"$id"'", "https://github.com/advisories/'"$id"'"] | unique | .[]' | sed 's/^/- /')

	title="osv: $id affects directus $VERSION"
	[ "$id" = "$TEST_ID" ] && title="[TEST] $title"

	body=$(jq -rn \
		--arg id "$id" --arg ver "$VERSION" --arg cve "$cve" --arg sev "$sev" \
		--arg fixed "${fixed:-none listed}" --arg sum "$summary" --arg refs "$refs" \
		'"New GHSA affecting directus \($ver) (fork base) — auto-generated by `fork-osv-watch`.
## \($id)\($cve | if . == "" then "" else " (\(.))" end)
- severity: `\($sev)`
- fixed in: \($fixed)
- summary: \($sum)

### References
\($refs)

## Triage(规则见 SECURITY_BACKPORTS.md)
- [ ] CVSS ≥ 7 且本站配置可达 → 72h 内出补丁
- [ ] 其余 → 月度批处理
- 修复路径:重写实现(不 cherry-pick MSCL 代码)→ smoke 过 → tag `11.17.4-sec.N` → 台账
- 接受路径:追加 `fork-tools/.known-osv-ids` + 台账“已知未修复” + 关闭本 issue"')

	if [ "$DRY" = 1 ]; then
		echo "--- DRY issue ---"
		echo "TITLE: $title"
		printf '%s\n' "$body"
	else
		gh issue create --repo "$REPO" --label "$LABEL" --title "$title" --body "$body" >/dev/null
		echo "$id: issue created"
	fi
done
